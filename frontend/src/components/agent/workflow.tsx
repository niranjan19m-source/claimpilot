"use client";

import { AlertOctagon, CheckCircle2, Circle, CircleSlash, Loader2, UserRoundCheck } from "lucide-react";
import { motion } from "framer-motion";
import type { AgentEvent, InvestigationPlan, ToolResult } from "@/lib/api";
import { timeOf } from "@/lib/api";
import { Stage, StageState, deriveStages, toolPairs } from "@/lib/agent-events";
import { cn } from "@/lib/utils";
import { EvidenceChip, Tag } from "@/components/common";

const STATE_META: Record<StageState, { label: string; cls: string; icon: React.ReactNode }> = {
  pending: { label: "Pending", cls: "text-zinc-500", icon: <Circle size={15} /> },
  running: { label: "Running", cls: "text-info", icon: <Loader2 size={15} className="animate-spin" /> },
  completed: { label: "Completed", cls: "text-verified", icon: <CheckCircle2 size={15} /> },
  failed: { label: "Failed", cls: "text-risk", icon: <AlertOctagon size={15} /> },
  review: { label: "Requires human review", cls: "text-missing", icon: <UserRoundCheck size={15} /> },
  skipped: { label: "Not required", cls: "text-zinc-600", icon: <CircleSlash size={15} /> },
};

/** Vertical execution stepper — the 10 workflow stages, derived from real events. */
export function WorkflowStepper({ events, status, compact }: { events: AgentEvent[]; status?: string; compact?: boolean }) {
  const stages = deriveStages(events, status);
  return (
    <ol className="relative" aria-label="Investigation workflow">
      {stages.map((s, i) => <StageRow key={s.key} stage={s} last={i === stages.length - 1} index={i} compact={compact} />)}
    </ol>
  );
}

function StageRow({ stage, last, index, compact }: { stage: Stage; last: boolean; index: number; compact?: boolean }) {
  const m = STATE_META[stage.state];
  return (
    <li className="relative flex gap-3 pb-3.5 last:pb-0">
      {!last && <span aria-hidden className={cn("absolute left-[7px] top-5 bottom-0 w-px", stage.state === "completed" ? "bg-emerald-500/40" : "bg-white/10")} />}
      <span className={cn("relative z-10 mt-0.5 bg-card", m.cls)}>{m.icon}</span>
      <div className="min-w-0 flex-1">
        <div className="flex items-baseline justify-between gap-2">
          <span className={cn("text-[13px]", stage.state === "pending" || stage.state === "skipped" ? "text-zinc-500" : "font-medium text-foreground")}>
            <span className="mr-1.5 font-mono text-[10.5px] text-zinc-600">{String(index + 1).padStart(2, "0")}</span>{stage.label}
          </span>
          {stage.started && <span className="shrink-0 font-mono text-[10.5px] text-zinc-500">{timeOf(stage.started)}</span>}
        </div>
        {!compact && (
          <div className={cn("text-[11px]", m.cls)}>
            {m.label}{stage.note ? <span className="text-zinc-500"> · {stage.note}</span> : null}
          </div>
        )}
      </div>
    </li>
  );
}

/** Investigation plan: tasks generated by the planner, with live execution state per task. */
export function PlanPanel({ plan, events, ledger, onOpen }: {
  plan?: InvestigationPlan; events: AgentEvent[]; ledger: ToolResult[]; onOpen: (evidenceId: string) => void;
}) {
  if (!plan) return <div className="text-[13px] text-muted-foreground">The plan appears here once the planner runs.</div>;
  const pairs = toolPairs(events);
  const byTool = new Map<string, { id: string; state: "running" | "done" | "failed"; flags: number }>();
  for (const [id, p] of pairs) {
    const tool = (p.result ?? p.call)!.payload.tool;
    byTool.set(tool, { id, state: !p.result ? "running" : p.result.payload.ok ? "done" : "failed", flags: p.result?.payload.signals?.length ?? 0 });
  }
  const ledgerById = Object.fromEntries(ledger.map((e) => [e.id, e]));
  const extra = [...byTool.keys()].filter((t) => !plan.steps.some((s) => s.tool === t));
  return (
    <div>
      <div className="mb-2 flex flex-wrap gap-1.5">
        <Tag tone={plan.depth === "deep" ? "risk" : plan.depth === "light" ? "verified" : "info"}>{plan.depth} investigation</Tag>
        <Tag>{plan.source === "llm" ? "Planned by Claude" : "Rules baseline planner"}</Tag>
        <Tag>{plan.steps.length} tasks</Tag>
      </div>
      <p className="text-[12.5px] leading-relaxed text-muted-foreground">{plan.rationale}</p>
      {plan.hypotheses.length > 0 && (
        <div className="mt-3 rounded-lg border bg-raised p-3">
          <div className="mb-1.5 text-[10.5px] font-semibold uppercase tracking-[0.1em] text-zinc-500">Hypotheses under test</div>
          <ul className="space-y-1 text-[12.5px] text-zinc-300">{plan.hypotheses.map((h) => <li key={h} className="flex gap-2"><span className="text-zinc-600">—</span>{h}</li>)}</ul>
        </div>
      )}
      <ol className="mt-3 space-y-0.5">
        {plan.steps.map((s, i) => {
          const t = byTool.get(s.tool);
          return (
            <motion.li key={s.tool + i} initial={{ opacity: 0, x: -4 }} animate={{ opacity: 1, x: 0 }} transition={{ delay: i * 0.03 }}
              className="flex items-start gap-2.5 rounded-md px-2 py-1.5 hover:bg-white/[0.03]">
              <span className="mt-0.5">
                {!t ? <Circle size={14} className="text-zinc-600" /> : t.state === "running" ? <Loader2 size={14} className="animate-spin text-info" />
                  : t.state === "failed" ? <AlertOctagon size={14} className="text-missing" />
                    : t.flags ? <AlertOctagon size={14} className="text-risk" /> : <CheckCircle2 size={14} className="text-verified" />}
              </span>
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-1.5 text-[12.5px] font-medium">{s.label}
                  {t && <EvidenceChip id={t.id} entry={ledgerById[t.id]} onOpen={onOpen} />}
                  {t?.flags ? <Tag tone="risk">{t.flags} flag{t.flags > 1 ? "s" : ""}</Tag> : null}
                  {t?.state === "failed" && <Tag tone="missing">degraded</Tag>}
                </div>
                <div className="text-[11.5px] text-zinc-500">{s.reason}</div>
              </div>
            </motion.li>
          );
        })}
        {extra.map((tool) => {
          const t = byTool.get(tool)!;
          return (
            <li key={tool} className="flex items-center gap-2.5 px-2 py-1.5 text-[12.5px]">
              <CheckCircle2 size={14} className="text-info" />
              <span className="font-medium">{ledgerById[t.id]?.label ?? tool}</span>
              <EvidenceChip id={t.id} entry={ledgerById[t.id]} onOpen={onOpen} />
              <span className="text-[11px] text-zinc-500">added by the agent</span>
            </li>
          );
        })}
      </ol>
    </div>
  );
}
